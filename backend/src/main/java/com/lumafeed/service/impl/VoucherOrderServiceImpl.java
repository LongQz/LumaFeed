    private void createVoucherOrder(VoucherOrder voucherOrder) {
        Long userId = voucherOrder.getUserId();
        Long voucherId = voucherOrder.getVoucherId();
        // 创建锁对象
        RLock redisLock = redissonClient.getLock("lock:order:" + userId);
        // 尝试获取锁
        boolean isLock = redisLock.tryLock();
        // 判断
        if (!isLock) {
            throw new IllegalStateException("请勿重复提交订单");
        }

        try {
            transactionTemplate.executeWithoutResult(status -> {
                // 数据库唯一约束之外再做一次业务校验，防止 Redis 数据丢失后重复下单。
                int count = query().eq("user_id", userId).eq("voucher_id", voucherId).count();
                if (count > 0) {
                    throw new IllegalStateException("不能重复下单");
                }

                boolean success = seckillVoucherService.update()
                        .setSql("stock = stock - 1")
                        .eq("voucher_id", voucherId)
                        .gt("stock", 0)
                        .update();
                if (!success) {
                    throw new IllegalStateException("库存不足");
                }

                if (!save(voucherOrder)) {
                    throw new IllegalStateException("订单保存失败");
                }
            });
        } finally {
            redisLock.unlock();
        }
    }

    @Override
    public Result seckillVoucher(Long voucherId) {
        Long userId = UserHolder.getUser().getId();
        long orderId = redisIdWorker.nextId("order");
        // 1.执行lua脚本
        Long result = stringRedisTemplate.execute(
                SECKILL_SCRIPT,
                Collections.emptyList(),
                voucherId.toString(), userId.toString(), String.valueOf(orderId)
        );
        int r = result.intValue();
        // 2.判断结果是否为0
        if (r != 0) {
            // 2.1.不为0 ，代表没有购买资格
            return Result.fail(r == 1 ? "库存不足" : "不能重复下单");
        }

        VoucherOrder voucherOrder = new VoucherOrder()
                .setId(orderId)
                .setUserId(userId)
                .setVoucherId(voucherId);
        try {
            // Lua 完成 Redis 预扣库存后，同步完成数据库事务，避免只返回订单号但不落库。
            createVoucherOrder(voucherOrder);
            return Result.ok(orderId);
        } catch (Exception exception) {
            rollbackReservation(voucherId, userId);
            log.warn("秒杀下单失败，已回滚 Redis 预占: {}", exception.getMessage());
            return Result.fail(exception.getMessage());
        }
    }

    private void rollbackReservation(Long voucherId, Long userId) {
        stringRedisTemplate.opsForValue().increment("seckill:stock:" + voucherId);
        stringRedisTemplate.opsForSet().remove("seckill:order:" + voucherId, userId.toString());
    }

